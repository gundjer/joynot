// Handwriting letters as strokes (simple "ball and stick" print, the way schools teach it).
// Units: top line y=0, middle (dashed) line y=50, baseline y=100, descender y=135.
// Segment: ['L', x1, y1, x2, y2] = line, ['A', cx, cy, rx, ry, fromDeg, toDeg] = arc
// (0° = right, 90° = down; going from a bigger to a smaller angle draws counter-clockwise, like the letter c).
// Each glyph: { w: width, s: [stroke, stroke, ...] }, each stroke = [segment, ...] drawn without lifting the pencil.

const L = (x1, y1, x2, y2) => ['L', x1, y1, x2, y2];
const A = (cx, cy, rx, ry, a0, a1) => ['A', cx, cy, rx, ry, a0, a1];

