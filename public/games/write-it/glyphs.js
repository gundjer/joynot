/** Turn a glyph into point lists (one list per stroke), sampled about every `step` units. */
export function strokePoints(g, step = 3) {
  return g.s.map(stroke => {
    const pts = [];
    stroke.forEach(seg => {
      if (seg[0] === 'L') {
        const [, x1, y1, x2, y2] = seg, len = Math.hypot(x2 - x1, y2 - y1), n = Math.max(1, Math.ceil(len / step));
        for (let i = 0; i <= n; i++) pts.push([x1 + (x2 - x1) * i / n, y1 + (y2 - y1) * i / n]);
      } else {
        const [, cx, cy, rx, ry, a0, a1] = seg, len = Math.abs(a1 - a0) / 360 * Math.PI * (rx + ry), n = Math.max(2, Math.ceil(len / step));
        for (let i = 0; i <= n; i++) { const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180; pts.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]); }
      }
    });
    return pts;
  });
}

